/**
 * WEB ASSETS, COMPILED INTO THE CELL.
 *
 *   node cells/drive/scripts/build-web-assets.mjs
 *
 * The PWA manifest, the icons and the service worker were added under `web/`
 * and served with `readFileSync(join(__dirname, 'web', …))`. Live, every one of
 * them 404s, and had done since the day they were added — nothing on the
 * deployed cell had ever looked for them.
 *
 * The platform deploys a cell by reading its source out of S3 into a
 * `Record<string, string>`, bundling the entry, and shipping ONLY that bundle
 * plus `app.js` plus anything under `static/`. So `web/` never reaches the
 * Lambda's disk at all — and `static/` would not save the icons either, because
 * that read is `Buffer.toString('utf-8')` and a PNG does not survive being a
 * string. (`getObjectRaw` exists next door; making `static/` binary-safe is a
 * platform change and the right long-term fix. This is the cell-side one.)
 *
 * What does reach the Lambda is the bundle, so the assets travel inside it as
 * a generated module. `web/` stays the source of truth — the native shells copy
 * it verbatim into `dist/web` — and this writes what the cell serves from it.
 * `devtools/appshell.test.mjs` fails if the two drift.
 */
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const CELL = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const WEB = join(CELL, 'web');

/** The module body, as a string — exported so a test can compare it with what
 *  is checked in rather than trusting anyone to have run this. */
export async function render() {
const manifest = await readFile(join(WEB, 'manifest.webmanifest'), 'utf8');
const sw = await readFile(join(WEB, 'sw.js'), 'utf8');
const icons = {};
for (const name of (await readdir(join(WEB, 'icons'))).sort()) {
  icons[`icons/${name}`] = (await readFile(join(WEB, 'icons', name))).toString('base64');
}

const body = `// GENERATED by scripts/build-web-assets.mjs — do not edit.
// Source of truth is cells/drive/web/. Regenerate after changing anything there;
// devtools/appshell.test.mjs fails if this file and web/ disagree.
//
// It exists because the platform ships a cell as ONE bundle: files under web/
// never reach the Lambda's disk, so anything the cell serves has to be inside
// the module graph. See the head of the generator for the whole story.
/* eslint-disable */

/** The PWA manifest, verbatim. */
export const WEB_MANIFEST = ${JSON.stringify(manifest)};

/** The service worker source, with its build placeholder still in it. */
export const SERVICE_WORKER = ${JSON.stringify(sw)};

/** Icons by path under web/, base64 — the cell answers them as-is. */
export const WEB_ICONS: Record<string, string> = {
${Object.entries(icons).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}
};
`;
  return { body, manifest, sw, icons };
}

export const ASSETS_PATH = join(CELL, 'web-assets.ts');

// Only when run directly; importing this must not write anything.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { body, manifest, sw, icons } = await render();
  await writeFile(ASSETS_PATH, body);
  console.log(`web-assets.ts: manifest ${manifest.length}b, sw ${sw.length}b, `
    + `${Object.keys(icons).length} icons, ${(body.length / 1024).toFixed(0)}KB total`);
}
