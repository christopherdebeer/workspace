#!/usr/bin/env node
/**
 * vendor-playtest — copy the playtest engine (christopherdebeer/playtest) into
 * the jev · lab client so the Playtest experiment runs the SAME mechanics the
 * CLI runs, in the browser, with no agents.
 *
 *   node scripts/vendor-playtest.mjs <path-to-playtest-clone> [out-dir]
 *
 * out-dir defaults to cells/jev/client/playtest/engine (the jev · lab demo).
 * The @c15r/playtest cell's copy (cells/playtest/engine) is the git truth for
 * the engine going forward: mechanics are added and fixed THERE, so re-vendoring
 * over it would discard that work — it refuses unless --force.
 *
 * What changes on the way in (nothing else):
 *   - `./x.js` relative imports lose the `.js` (the cell bundler resolves
 *     `.ts`/`.tsx`/`/index.ts`, not NodeNext `.js` specifiers);
 *   - `fs` / `path` / `url` point at in-memory shims under `shims/`, rooted at
 *     /pt (so GAMES_DIR = /pt/games, MECHANICS_DIR = /pt/mechanics);
 *   - `process.pid` becomes 1 (the lock file content only).
 * `yaml` stays a bare import — the bundler serves it from esm.sh (pinned in
 * client/imports.json). The CLI, `turns.ts` (fs.watch waits) and `cleanup.ts`
 * are left behind: the lab drives the engine in-process.
 * The source commit is pinned in engine/VENDOR.json.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

const src = process.argv[2];
if (!src) {
  console.error('usage: vendor-playtest.mjs <playtest-clone>');
  process.exit(2);
}
const OUT = join(process.cwd(), process.argv[3] && !process.argv[3].startsWith('--') ? process.argv[3] : 'cells/jev/client/playtest/engine');
if (OUT.includes('cells/playtest/') && existsSync(join(OUT, 'VENDOR.json')) && !process.argv.includes('--force')) {
  console.error(`${OUT} already holds the engine and is its git truth (mechanics evolve there). Pass --force to overwrite.`);
  process.exit(1);
}
const SKIP = new Set(['src/cli', 'src/core/cleanup.ts', 'src/core/turns.ts', 'src/index.ts']);

function walk(dir, out = []) {
  for (const name of readdirSync(join(src, dir))) {
    const rel = join(dir, name);
    if (SKIP.has(rel)) continue;
    if (statSync(join(src, rel)).isDirectory()) walk(rel, out);
    else if (rel.endsWith('.ts') && !rel.endsWith('.test.ts')) out.push(rel);
  }
  return out;
}

rmSync(OUT, { recursive: true, force: true });
const files = walk('src');
for (const rel of files) {
  const dest = join(OUT, rel.replace(/^src\//, ''));
  const shims = relative(dirname(dest), join(OUT, 'shims')) || '.';
  const shimPath = (n) => `${shims.startsWith('.') ? shims : './' + shims}/${n}`;
  let code = readFileSync(join(src, rel), 'utf8')
    .replace(/(from\s+['"])(\.{1,2}\/[^'"]+?)\.js(['"])/g, '$1$2$3')
    .replace(/(import\(\s*['"])(\.{1,2}\/[^'"]+?)\.js(['"]\s*\))/g, '$1$2$3')
    .replace(/from\s+['"](fs|node:fs)['"]/g, `from '${shimPath('fs')}'`)
    .replace(/from\s+['"](path|node:path)['"]/g, `from '${shimPath('path')}'`)
    .replace(/from\s+['"](url|node:url)['"]/g, `from '${shimPath('url')}'`)
    .replace(/process\.pid/g, '1');
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, code);
}

// Data the engine reads through fs (mechanic index + registered mechanics),
// as a TS module the bundler can load (it would parse raw .json as TS).
const data = {
  '/pt/mechanics/index.json': readFileSync(join(src, 'mechanics/index.json'), 'utf8'),
  '/pt/shared/registered-mechanics.json': readFileSync(join(src, 'shared/registered-mechanics.json'), 'utf8'),
};
mkdirSync(join(OUT, 'shims'), { recursive: true });
writeFileSync(join(OUT, 'shims/data.ts'), `/* generated by scripts/vendor-playtest.mjs — do not edit */\nexport const SEED_FILES: Record<string, string> = ${JSON.stringify(data)};\n`);

writeFileSync(
  join(OUT, 'shims/fs.ts'),
  `/* In-memory fs for the vendored playtest engine (generated by scripts/vendor-playtest.mjs).
 * Only the calls the engine makes. One game per page; the lab resets it. */
import { SEED_FILES } from './data';

const files = new Map<string, string>(Object.entries(SEED_FILES));
const dirs = new Set<string>(['/', '/pt']);

const norm = (p: string) => p.replace(/\\/+/g, '/').replace(/\\/$/, '') || '/';
const parentsOf = (p: string) => {
  const out: string[] = [];
  let cur = norm(p);
  while (cur.includes('/') && cur !== '/') {
    cur = cur.slice(0, cur.lastIndexOf('/')) || '/';
    out.push(cur);
  }
  return out;
};
function enoent(p: string): Error {
  return Object.assign(new Error(\`ENOENT: no such file or directory, '\${p}'\`), { code: 'ENOENT' });
}

export function existsSync(p: string): boolean {
  const k = norm(p);
  return files.has(k) || dirs.has(k);
}
export function readFileSync(p: string, _enc?: unknown): string {
  const k = norm(p);
  const v = files.get(k);
  if (v === undefined) throw enoent(k);
  return v;
}
export function writeFileSync(p: string, data: string, opts?: { flag?: string } | string): void {
  const k = norm(p);
  if (typeof opts === 'object' && opts?.flag === 'wx' && files.has(k)) {
    throw Object.assign(new Error(\`EEXIST: file already exists, '\${k}'\`), { code: 'EEXIST' });
  }
  files.set(k, String(data));
  parentsOf(k).forEach((d) => dirs.add(d));
}
export function appendFileSync(p: string, data: string): void {
  const k = norm(p);
  files.set(k, (files.get(k) ?? '') + String(data));
  parentsOf(k).forEach((d) => dirs.add(d));
}
export function mkdirSync(p: string, _opts?: unknown): void {
  const k = norm(p);
  dirs.add(k);
  parentsOf(k).forEach((d) => dirs.add(d));
}
export function unlinkSync(p: string): void {
  if (!files.delete(norm(p))) throw enoent(p);
}
export function readdirSync(p: string): string[] {
  const k = norm(p);
  if (!dirs.has(k)) throw enoent(k);
  const pre = k === '/' ? '/' : k + '/';
  const names = new Set<string>();
  for (const f of [...files.keys(), ...dirs]) {
    if (f.startsWith(pre) && f !== k) names.add(f.slice(pre.length).split('/')[0]);
  }
  return [...names].sort();
}
export function statSync(p: string): { isDirectory(): boolean; isFile(): boolean; mtimeMs: number } {
  const k = norm(p);
  if (!files.has(k) && !dirs.has(k)) throw enoent(k);
  const dir = dirs.has(k);
  return { isDirectory: () => dir, isFile: () => !dir, mtimeMs: 0 };
}
export function watch(): never {
  throw new Error('fs.watch is not available in the lab');
}
export type FSWatcher = never;

/** Lab-only: drop every game's state and logs (seed data stays). */
export function resetGames(): void {
  for (const k of [...files.keys()]) if (k.startsWith('/pt/games/')) files.delete(k);
  for (const d of [...dirs]) if (d.startsWith('/pt/games/')) dirs.delete(d);
}
/** Lab-only: read every file under a prefix (e.g. a game's logs). */
export function filesUnder(prefix: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of files) if (k.startsWith(prefix)) out[k] = v;
  return out;
}
export default { existsSync, readFileSync, writeFileSync, appendFileSync, mkdirSync, unlinkSync, readdirSync, statSync, watch };
`,
);
writeFileSync(
  join(OUT, 'shims/path.ts'),
  `/* POSIX path subset for the vendored engine (generated). */
export function join(...parts: string[]): string {
  const stack: string[] = [];
  const abs = parts[0]?.startsWith('/');
  for (const seg of parts.join('/').split('/')) {
    if (seg === '..') stack.pop();
    else if (seg && seg !== '.') stack.push(seg);
  }
  return (abs ? '/' : '') + stack.join('/');
}
export function dirname(p: string): string {
  const i = p.replace(/\\/$/, '').lastIndexOf('/');
  return i <= 0 ? (p.startsWith('/') ? '/' : '.') : p.slice(0, i);
}
export function basename(p: string, ext?: string): string {
  const b = p.replace(/\\/$/, '').split('/').pop() ?? '';
  return ext && b.endsWith(ext) ? b.slice(0, -ext.length) : b;
}
export default { join, dirname, basename };
`,
);
writeFileSync(
  join(OUT, 'shims/url.ts'),
  `/* Every vendored module lives at /pt/src/<dir>/_ as far as path maths goes, so
 * PROJECT_ROOT = /pt, GAMES_DIR = /pt/games, MECHANICS_DIR = /pt/mechanics.
 * (All engine callers are in src/core, two levels below the root.) */
export function fileURLToPath(_url: string): string {
  return '/pt/src/core/_.js';
}
export default { fileURLToPath };
`,
);

// Every `engine_mechanics.<key>` the engine actually reads — a declared key
// outside this set configures nothing.
const consumed = new Set();
for (const rel of files) {
  const text = readFileSync(join(src, rel), 'utf8');
  for (const m of text.matchAll(/engine_mechanics\??\.\??([a-z_]+)|engine_mechanics\[['"]([a-z_]+)/g)) consumed.add(m[1] ?? m[2]);
}
writeFileSync(
  join(OUT, 'consumed-keys.ts'),
  `/* generated by scripts/vendor-playtest.mjs — engine_mechanics keys the engine reads */\nexport const CONSUMED_KEYS = new Set<string>(${JSON.stringify([...consumed].sort())});\n`,
);

// The catalogue's game definitions, as lab presets (RULES.md text by slug).
const presets = {};
for (const g of readdirSync(join(src, 'games')).sort()) {
  try {
    presets[g] = readFileSync(join(src, 'games', g, 'RULES.md'), 'utf8');
  } catch {
    /* not a game folder */
  }
}
writeFileSync(
  join(OUT, 'presets.ts'),
  `/* generated by scripts/vendor-playtest.mjs — the playtest catalogue's RULES.md files */\nexport const PRESETS: Record<string, string> = ${JSON.stringify(presets, null, 1)};\n`,
);

const commit = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const info = { source: 'https://github.com/christopherdebeer/playtest', commit, files: files.length, vendoredBy: 'scripts/vendor-playtest.mjs' };
writeFileSync(join(OUT, 'VENDOR.json'), JSON.stringify(info, null, 2) + '\n');
writeFileSync(join(OUT, 'vendor-info.ts'), `/* generated by scripts/vendor-playtest.mjs */\nconst VENDOR = ${JSON.stringify(info)};\nexport default VENDOR;\n`);
console.log(`vendored ${files.length} files from ${commit.slice(0, 7)} → ${relative(process.cwd(), OUT)}`);
