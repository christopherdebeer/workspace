#!/usr/bin/env node
/**
 * Regenerate cells/viewers/renderers.gen.ts — the committed IIFE bundle behind
 * `ui://@c15r/viewers/renderers.js` (ADR-0044 Inc 4). Same committed-artifact
 * pattern as services/cells/cell-ui.generated.ts: the cell's server handler
 * imports the string and serves it, so no runtime build or filesystem layout
 * assumption is needed in the Lambda. Run after editing
 * cells/viewers/client/renderers-entry.ts or cells/viewers/client/main.ts.
 */
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const out = await build({
  entryPoints: ['cells/viewers/client/renderers-entry.ts'],
  bundle: true,
  format: 'iife',
  minify: true,
  write: false,
  target: 'es2020',
});
const js = out.outputFiles[0].text;
const gen = `/* GENERATED by scripts/build-viewers-renderers.mjs — do not edit.
 * The classic-script bundle served at /renderers.js (ui://@c15r/viewers/renderers.js):
 * self-registers window.__parcRender.{json,csv,mermaid} from the same pure viewer
 * implementations client/main.ts exports (reference, not copy — this is a BUILD of
 * that module, not a fork). See client/renderers-entry.ts. */
export const RENDERERS_JS: string = ${JSON.stringify(js)};
`;
writeFileSync('cells/viewers/renderers.gen.ts', gen);
console.log(`renderers.gen.ts: ${(js.length / 1024).toFixed(1)}KB bundled`);
